/**
 * Render a markdown PR comment from a validated artifact.
 * Every user-/artifact-controlled string goes through esc().
 */

export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ');
}

export const COMMENT_MARKER = '<!-- sbom-diff-sticky -->';

export function formatComment(artifact) {
  const s = artifact.summary || {};
  const c = artifact.changes || {};
  const lines = [];
  lines.push(COMMENT_MARKER);
  lines.push('## sbom-diff');
  lines.push('');
  lines.push(
    `Dependency changes on this PR: **${num(s.added)}** added, **${num(s.removed)}** removed, **${num(s.upgraded)}** upgraded, **${num(s.downgraded)}** downgraded.`,
  );
  if (num(s.vulnerable) > 0) {
    lines.push('');
    lines.push(
      `⚠️ **${num(s.vulnerable)}** changed package(s) have known vulnerabilities in OSV.`,
    );
  } else {
    lines.push('');
    lines.push('No known vulnerabilities reported by OSV for added/upgraded packages.');
  }
  lines.push('');

  appendSection(lines, 'Added', c.added, 'added');
  appendSection(lines, 'Removed', c.removed, 'removed');
  appendSection(lines, 'Upgraded', c.upgraded, 'upgraded');
  appendSection(lines, 'Downgraded', c.downgraded, 'downgraded');

  lines.push('---');
  lines.push(
    '<sub>Generated by sbom-diff. Vulnerability data from [OSV](https://osv.dev). Treat findings as leads, not a complete audit.</sub>',
  );
  lines.push('');
  return lines.join('\n');
}

function num(n) {
  return Number.isFinite(Number(n)) ? Number(n) : 0;
}

function appendSection(lines, title, list, kind) {
  if (!Array.isArray(list) || list.length === 0) return;
  lines.push(`### ${title}`);
  lines.push('');
  if (kind === 'upgraded' || kind === 'downgraded') {
    lines.push('| Ecosystem | Package | From | To | Vulns |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const p of list.slice(0, 200)) {
      lines.push(
        `| ${esc(p.ecosystem)} | ${esc(p.name)} | ${esc(p.from)} | ${esc(p.to || p.version)} | ${vulnCell(p)} |`,
      );
    }
  } else {
    lines.push('| Ecosystem | Package | Version | Vulns |');
    lines.push('| --- | --- | --- | --- |');
    for (const p of list.slice(0, 200)) {
      lines.push(
        `| ${esc(p.ecosystem)} | ${esc(p.name)} | ${esc(p.version)} | ${kind === 'removed' ? '—' : vulnCell(p)} |`,
      );
    }
  }
  if (list.length > 200) {
    lines.push('');
    lines.push(`_…and ${list.length - 200} more._`);
  }
  lines.push('');
  // Detail vulns
  const withV = list.filter((p) => p.vulnerabilities && p.vulnerabilities.length);
  if (withV.length && kind !== 'removed') {
    lines.push('<details>');
    lines.push(`<summary>Vulnerability details (${withV.length})</summary>`);
    lines.push('');
    for (const p of withV.slice(0, 50)) {
      lines.push(`**${esc(p.name)}@${esc(p.to || p.version)}** (${esc(p.ecosystem)})`);
      for (const v of p.vulnerabilities.slice(0, 10)) {
        lines.push(
          `- ${esc(v.id)} — ${esc(v.severity)} — ${esc(v.summary)}`,
        );
      }
      lines.push('');
    }
    lines.push('</details>');
    lines.push('');
  }
}

function vulnCell(p) {
  const n = (p.vulnerabilities && p.vulnerabilities.length) || 0;
  if (!n) return '0';
  const ids = p.vulnerabilities.slice(0, 3).map((v) => esc(v.id)).join(', ');
  return n <= 3 ? ids : `${ids} +${n - 3}`;
}
